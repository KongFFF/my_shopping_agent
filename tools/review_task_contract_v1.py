def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def verify_frozen_package():
    manifest = json.loads((PACKAGE / "manifest.json").read_text(encoding="utf-8"))
    for name, expected in manifest["artifact_sha256"].items():
        if sha(PACKAGE / name) != expected:
            raise ValueError(f"Frozen v1 artifact changed: {name}")
    return manifest


def build_reviews():
    manifest = verify_frozen_package()
    pending = [json.loads(line) for line in (PACKAGE / "quarantine.jsonl").read_text(encoding="utf-8").splitlines()]
    path = ROOT / "upstream/shopping-grpo-longhorizon/environments/ShopSimulator/shop_env/data/fine_items_eval_train_all.json.gz"
    with gzip.open(path, "rb") as handle:
        source = handle.read()
    if hashlib.sha256(source).hexdigest() != manifest["original_catalog_sha256"]:
        raise ValueError("Catalog differs from the frozen v1 source snapshot")
    products = {str(p["asin"]): p for p in json.loads(source)}
    definitions = {}
    for category, entries in zip(CATEGORIES, (RULES, POLICIES, ANNOTATIONS, METADATA, BOUNDARIES, CONFLICTS)):
        for tid, judgment in entries.items():
            if tid in definitions:
                raise ValueError(f"Duplicate judgment: {tid}")
            definitions[tid] = (category, judgment)
    if set(definitions) != {r["task_id"] for r in pending} or len(pending) != 107:
        raise ValueError("First-pass coverage must equal the 107 quarantined IDs exactly")
    reviews = []
    for task in pending:
        tid = task["task_id"]
        category, (quote, interpretation, action) = definitions[tid]
        if quote not in task["query"]:
            raise ValueError(f"Quote is not verbatim query evidence: {tid}: {quote}")
        product = products[task["asin"]]
        instructions = [i for i in product["instructions"] if i["instruction"] == task["query"]]
        if len(instructions) != 1:
            raise ValueError(f"Cannot uniquely bind source instruction: {tid}")
        facts = []
        for axis, options in product.get("customization_options", {}).items():
            selected = task["selected_gold_options"].get(axis)
            matches = [e for e in options if selected is not None and normalized(e["value"]) == normalized(selected)]
            facts.append({"axis": axis, "selected_in_v1_audit": selected,
                          "matched_options": [{"value": e["value"], "price": e.get("price"), "sku_id": e.get("asin")} for e in matches],
                          "axis_candidate_count": len(options)})
        candidates = []
        for axis, value in CANDIDATES.get(tid, {}).items():
            matches = [e for e in product["customization_options"][axis] if e["value"] == value]
